import { formatToman, toFa } from "@/lib/utils";
import { ARKAN } from "@/lib/documents/company";
import { faDate, tomanInWords } from "@/lib/documents/format";

/**
 * قالب پیش‌فرض قرارداد خدمات مشاوره‌ی آرکان (Markdown).
 * موقع ساخت قرارداد، مقادیر طرفین/مبلغ/مدت مستقیم در متن جایگذاری می‌شود؛
 * بعداً در ویرایشگر قابل تغییر است و دکمه‌ی AI هم می‌تواند بازنویسی‌اش کند.
 *
 * اگر قرارداد از روی پروپوزال ساخته شود، مراحل، خروجی‌ها، موارد خارج از دامنه و
 * شرایط پرداختِ بسته‌ی انتخابی کلاینت هم در ماده‌های مربوط می‌نشیند.
 * شماره‌ی ماده‌ها خودکار است؛ تیترها «## ماده N — عنوان» نوشته می‌شوند تا در
 * نسخه‌ی کلاینت و PDF درست رندر شوند.
 */

export type ContractContext = {
  clientName: string;
  companyName: string | null;
  dealTitle: string | null;
  amountToman: number;
  startDate: string | null; // YYYY-MM-DD
  durationLabel: string | null;
  challenge?: string | null;
  /** از پروپوزال تأییدشده */
  proposalNo?: string | null;
  packageName?: string | null;
  scope?: string[];
  deliverables?: string[];
  exclusions?: string[];
  paymentNote?: string | null;
};

const BLANK = "................";

const DEFAULT_SCOPE = [
  "**شناخت و عارضه‌یابی:** بررسی وضع موجود کسب‌وکار، داده‌های فروش و مالی، مشتریان و رقبا.",
  "**طراحی استراتژی:** تعیین جهت رشد، اولویت‌ها و مزیت رقابتی در کارگاه‌های مشترک با مدیران کارفرما.",
  "**نقشه‌ی راه اجرایی:** تبدیل استراتژی به برنامه‌ی زمان‌بندی‌شده با مسئول و شاخص سنجش هر اقدام.",
  "**همراهی در اجرا و پایش:** جلسات پیگیری منظم و بازبینی شاخص‌ها برای اصلاح مسیر.",
];

const DEFAULT_DELIVERABLES = [
  "گزارش مکتوب پایان هر فاز.",
  "سند استراتژی و نقشه‌ی راه اجرایی.",
  "فهرست شاخص‌های کلیدی عملکرد و روال بازبینی آن‌ها.",
];

const DEFAULT_EXCLUSIONS = [
  "اجرای عملیاتی کارها به‌جای کارکنان کارفرما، مانند فروش، تولید محتوا یا مدیریت تبلیغات.",
  "جذب و استخدام نیرو.",
  "هزینه‌های اجرایی مانند تبلیغات، نرم‌افزار و خرید خدمات از اشخاص ثالث.",
  "مشاوره‌ی حقوقی، مالیاتی و حسابرسی.",
];

const bullets = (items: string[]) => items.map((x) => `- ${x}`).join("\n");

export function buildDefaultContract(ctx: ContractContext): string {
  const client = ctx.companyName
    ? `${ctx.companyName} به نمایندگی ${ctx.clientName}`
    : ctx.clientName;
  const subject =
    ctx.dealTitle ?? "ارائه‌ی خدمات مشاوره‌ی استراتژی و رشد کسب‌وکار";
  const amount =
    ctx.amountToman > 0
      ? `${formatToman(ctx.amountToman)} (${tomanInWords(ctx.amountToman)})`
      : `${BLANK} تومان`;

  const source = ctx.proposalNo
    ? `\n\nاین قرارداد بر پایه‌ی پیشنهاد همکاری شماره‌ی **${ctx.proposalNo}**${
        ctx.packageName ? ` و بسته‌ی انتخابی «**${ctx.packageName}**»` : ""
      } تنظیم شده است که به تأیید کارفرما رسیده است.`
    : "";

  const payment = ctx.paymentNote?.trim()
    ? `حق‌الزحمه‌ی مشاور جمعاً **${amount}** است و به این ترتیب پرداخت می‌شود: **${ctx.paymentNote.trim()}**.\n\nهر پرداخت ظرف ۷ روز کاری از اعلام مشاور انجام می‌شود.`
    : `حق‌الزحمه‌ی مشاور جمعاً **${amount}** است که به شرح زیر پرداخت می‌شود:

- **۴۰٪** هم‌زمان با تأیید قرارداد (پیش‌پرداخت)؛
- **۳۰٪** پس از تحویل گزارش فاز شناخت و طراحی استراتژی؛
- **۳۰٪** در پایان دوره و پس از ارائه‌ی گزارش نهایی.

هر پرداخت ظرف ۷ روز کاری از اعلام مشاور انجام می‌شود.`;

  const articles: [string, string][] = [
    [
      "طرفین قرارداد",
      `این قرارداد میان **${ARKAN.legalName}** (${ARKAN.tagline}) به نمایندگی ${ARKAN.repName}، ${ARKAN.repTitle}، به نشانی ${ARKAN.city} (که از این پس «مشاور» نامیده می‌شود) و **${client}** (که از این پس «کارفرما» نامیده می‌شود) منعقد می‌گردد.`,
    ],
    [
      "موضوع قرارداد",
      `${subject}${ctx.challenge ? `، با تمرکز بر چالش اعلام‌شده‌ی کارفرما: ${ctx.challenge}` : ""}.${source}

خدمات بر پایه‌ی متدولوژی «چهار رکن» آرکان ارائه می‌شود: **استراتژی** (جهت‌گیری و مزیت رقابتی)، **ساختار** (سازمان و فرایندها)، **بازار** (برند، بازاریابی و فروش) و **اجرا** (تبدیل برنامه به نتیجه‌ی قابل‌اندازه‌گیری).`,
    ],
    [
      "شرح خدمات و مراحل اجرا",
      `خدمات مشاور در مراحل زیر انجام می‌شود:\n\n${bullets(ctx.scope?.length ? ctx.scope : DEFAULT_SCOPE)}`,
    ],
    [
      "خروجی‌های تحویلی",
      `مشاور در طول قرارداد این خروجی‌ها را تحویل کارفرما می‌دهد:\n\n${bullets(
        ctx.deliverables?.length ? ctx.deliverables : DEFAULT_DELIVERABLES
      )}`,
    ],
    [
      "مدت قرارداد",
      `مدت اجرای این قرارداد **${ctx.durationLabel || BLANK}** از تاریخ **${
        ctx.startDate ? faDate(ctx.startDate) : BLANK
      }** است و با توافق کتبی طرفین قابل تمدید است. تأخیر ناشی از تأمین‌نشدن اطلاعات یا تصمیم‌های کارفرما، به مدت قرارداد افزوده می‌شود.`,
    ],
    ["مبلغ قرارداد و شرایط پرداخت", payment],
    [
      "تعهدات مشاور",
      `1. ارائه‌ی خدمات با استانداردهای حرفه‌ای و در چارچوب زمان‌بندی توافق‌شده؛
2. معرفی یک مشاور راهبر مشخص به‌عنوان مسئول پروژه و نقطه‌ی تماس کارفرما؛
3. ارائه‌ی گزارش مکتوب در پایان هر فاز؛
4. رازداری کامل نسبت به اطلاعات کارفرما مطابق ماده‌ی محرمانگی.

تعهد مشاور از نوع **تعهد به فعالیت** است، نه تعهد به نتیجه: مشاور دانش، روش و همراهی خود را به‌طور کامل به کار می‌گیرد، اما نتیجه‌ی نهایی به شرایط بازار و اجرای کارفرما نیز بستگی دارد.`,
    ],
    [
      "تعهدات کارفرما",
      `1. در دسترس قراردادن اطلاعات، اسناد و آمار موردنیاز پروژه در زمان مقرر؛
2. معرفی نماینده‌ی تام‌الاختیار برای هماهنگی و تصمیم‌گیری و حضور او در جلسات کلیدی؛
3. پرداخت به‌موقع مبالغ قرارداد مطابق ماده‌ی مبلغ و شرایط پرداخت.`,
    ],
    [
      "موارد خارج از دامنه",
      `موارد زیر خارج از موضوع این قرارداد است و در صورت نیاز، با توافق کتبی و برآورد جداگانه انجام می‌شود:\n\n${bullets(
        ctx.exclusions?.length ? ctx.exclusions : DEFAULT_EXCLUSIONS
      )}`,
    ],
    [
      "محرمانگی و مالکیت خروجی‌ها",
      `کلیه‌ی اطلاعات تجاری، مالی و راهبردی که در اجرای این قرارداد میان طرفین مبادله می‌شود محرمانه است و افشای آن به اشخاص ثالث بدون اجازه‌ی کتبی طرف دیگر، تا **دو سال** پس از پایان قرارداد ممنوع است.

پس از تسویه‌ی کامل، مالکیت خروجی‌های تحویلی با کارفرماست. مشاور حق استفاده از روش‌ها و ابزارهای عمومی خود را در پروژه‌های دیگر حفظ می‌کند و نام کارفرما را فقط با اجازه‌ی کتبی او در سوابق خود ذکر می‌کند.`,
    ],
    [
      "فسخ قرارداد",
      "هر یک از طرفین می‌تواند با اعلام کتبی **۱۵ روزه** قرارداد را فسخ کند. در صورت فسخ، هزینه‌ی خدمات انجام‌شده تا تاریخ فسخ محاسبه و تسویه می‌شود و مشاور خروجی‌های آماده‌شده تا همان تاریخ را تحویل می‌دهد.",
    ],
    [
      "حل اختلاف",
      "اختلافات ناشی از تفسیر یا اجرای این قرارداد ابتدا از راه گفت‌وگوی دوستانه و در صورت نرسیدن به توافق، از طریق داوری مرضی‌الطرفین حل‌وفصل می‌شود.",
    ],
  ];

  const total = articles.length + 1;
  articles.push([
    "نسخ قرارداد و تأیید آنلاین",
    `این قرارداد در **${toFa(total)} ماده** تنظیم شده است. تأیید آنلاین آن از طریق لینک اختصاصی کارفرما، همراه با ثبت نام تأییدکننده، زمان و نشانی IP، به‌منزله‌ی پذیرش کلیه‌ی مفاد آن از سوی کارفرماست.`,
  ]);

  return articles
    .map(([title, body], i) => `## ماده ${toFa(i + 1)} — ${title}\n\n${body}`)
    .join("\n\n");
}
